/* ---------------------------------------------------------------------------
 * Fenel LLVM runtime shim — C side of the Phase 16 effectful-compilation ABI.
 *
 * Provides:
 *   - Boxing helpers (`fenel_box_num` / `fenel_unbox_num` / `fenel_box_bool`
 *     / `fenel_unbox_bool`) that LLVM-emitted IR calls when a value crosses
 *     the host-pointer boundary. Phase 14's `coerceDomain` lowering targets
 *     these symbols.
 *   - String-literal helper `fenel_lit_string(ptr, len)` — Phase 16 added.
 *     The lowering interns each CeLit string into the per-module pool +
 *     emits one `@.str.<i>` private constant; this helper accepts the
 *     constant's pointer + UTF-8 byte length and returns the host-managed
 *     value pointer. Implementation: passthrough — the constant lives in
 *     static memory and is null-terminated, so the same pointer serves as
 *     the host-side string handle.
 *   - String concatenation `fenel_concat(ptr, ptr) -> ptr` — declared by
 *     the Phase 14 LLVM bootstrap when `concat` is in the body.
 *   - The handler registry (`fenel_register_handler` / `fenel_lookup_handler`
 *     / `fenel_reset_handlers`) that Phase 16's effect dispatch routes
 *     through. Per-`(Class, method)` shim functions (e.g.
 *     `fenel_HasStateIO_set`) are auto-generated by the test harness from
 *     `LlvmModule.effectImports` so this core file stays effect-class-
 *     agnostic; the design admits hand-written shims when a deployment
 *     prefers them.
 *
 * Linkage convention: the test harness compiles this file together with
 * the LLVM-emitted `.ll` + the auto-generated per-(Class, method) shim into
 * one shared object via `clang -shared`. Bun's FFI (`bun:ffi`) loads the
 * shared object and binds the C symbols. The host side's
 * `fenel_register_handler` calls — invoked by JS via FFI before the entry
 * function runs — populate the handler table; the LLVM-emitted code's
 * effect calls dispatch through `fenel_lookup_handler` at run time.
 *
 * Phase 16 picks the **global handler registry** ABI variant per
 * `design/effectful-compilation.md`: no per-call-site `%ctx` operand
 * (effectful callees keep the same LLVM signature as pure ones), the shim
 * is simpler, and the per-call lookup overhead is acceptable for the
 * bootstrap. Per-call-site `%ctx` threading lands when a real performance
 * case forces it.
 * ---------------------------------------------------------------------------
 */

#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* ---------------------------------------------------------------------------
 * Boxing helpers — domain conversions across the host-pointer boundary.
 *
 * Phase 14's lowering emits calls to these when a Fenel `Number` (LLVM
 * `double`) or `Bool` (`i1`) needs to cross into / out of `ptr`-typed
 * territory (effect-call args / runtime-helper args).
 *
 * Numbers box as a heap-allocated `double *`; booleans box as the integer
 * value reinterpreted as `void *` (the LSB carries the bool — no heap
 * allocation needed). The matching unbox is the inverse.
 *
 * Lifetime: boxed numbers leak. The bootstrap doesn't ship a GC; for the
 * test loop the leaks are bounded (one per effect call per invocation),
 * acceptable for a bootstrap that runs single-call test cases. A real
 * deployment would route through a host-managed value pool / Bun-side
 * pinned buffers / a Fenel-side GC.
 * ---------------------------------------------------------------------------
 */

double fenel_unbox_num(void *v) { return *(double *)v; }

int8_t fenel_unbox_bool(void *v) { return ((intptr_t)v) != 0 ? 1 : 0; }

void *fenel_box_num(double v) {
  double *p = (double *)malloc(sizeof(double));
  if (p == NULL) return NULL;
  *p = v;
  return (void *)p;
}

void *fenel_box_bool(int8_t v) { return (void *)(intptr_t)(v ? 1 : 0); }

/* ---------------------------------------------------------------------------
 * String literal helper — Phase 16
 *
 * The LLVM lowering emits `call ptr @fenel_lit_string(ptr @.str.<i>, i64
 * <utf8-byte-length>)` for each CeLit string. The string content lives in
 * static memory inside the compiled module; the pointer is null-terminated
 * (the @.str.<i> private constant declares one extra `\00` byte after the
 * UTF-8 payload).
 *
 * Implementation: passthrough — the static pointer IS the host-side string
 * value. The length argument rides along so a future variant can copy the
 * bytes into a host-owned pool (e.g. for interning or refcounting); the
 * bootstrap doesn't need that.
 * ---------------------------------------------------------------------------
 */

void *fenel_lit_string(void *ptr, int64_t len) {
  (void)len;
  return ptr;
}

/* ---------------------------------------------------------------------------
 * String concatenation — backs Phase 14's `@fenel_concat` extern.
 *
 * The C-side fallback for the bootstrap: allocate a new buffer holding the
 * concatenation of two null-terminated strings. Same lifetime caveat as
 * `fenel_box_num` — the buffer is never freed; bootstrap-only.
 * ---------------------------------------------------------------------------
 */

void *fenel_concat(void *a, void *b) {
  const char *as = (const char *)a;
  const char *bs = (const char *)b;
  size_t la = (as != NULL) ? strlen(as) : 0;
  size_t lb = (bs != NULL) ? strlen(bs) : 0;
  char *out = (char *)malloc(la + lb + 1);
  if (out == NULL) return NULL;
  if (la > 0) memcpy(out, as, la);
  if (lb > 0) memcpy(out + la, bs, lb);
  out[la + lb] = '\0';
  return (void *)out;
}

/* ---------------------------------------------------------------------------
 * Handler registry — the Phase 16 effect-dispatch substrate.
 *
 * Keyed by `"<Class>:<method>"` (the canonical form the per-(Class, method)
 * shim functions look up). Each entry stores:
 *   - `invoke` — the function pointer the JS host registered (a Bun
 *     `JSCallback.ptr`). Signature: `void *(*)(void *env, void **args, int n)`.
 *   - `env`    — the closure's environment pointer; opaque to C, threaded
 *     through to the JS callback so it can recover its bound state.
 *
 * Lookup is linear because the bootstrap registers a handful of handlers
 * per test (typically 2–3); a hash table is overkill. A real deployment
 * with hundreds of effects would swap for `khash` / `uthash`.
 *
 * Threading: the registry is global and unsynchronised — the bootstrap is
 * single-threaded. Per-thread or per-instantiation registries (matching
 * the brief's "per-call-site %ctx threading lands when forced") are a
 * follow-on phase.
 * ---------------------------------------------------------------------------
 */

typedef void *(*FenelHandlerFn)(void *env, void **args, int n);

typedef struct {
  char *key;            /* owned copy — registry duplicates the caller's key */
  FenelHandlerFn invoke;
  void *env;
} FenelHandlerEntry;

#define FENEL_MAX_HANDLERS 128

static FenelHandlerEntry g_handlers[FENEL_MAX_HANDLERS];
static int g_n_handlers = 0;

void fenel_register_handler(const char *key, FenelHandlerFn invoke, void *env) {
  if (key == NULL || invoke == NULL) return;
  /* Replace if a previous registration exists for the same key (idempotent
   * re-binding lets the test harness re-register handlers between cases). */
  for (int i = 0; i < g_n_handlers; i++) {
    if (strcmp(g_handlers[i].key, key) == 0) {
      g_handlers[i].invoke = invoke;
      g_handlers[i].env = env;
      return;
    }
  }
  if (g_n_handlers >= FENEL_MAX_HANDLERS) return;
  size_t klen = strlen(key);
  char *kcopy = (char *)malloc(klen + 1);
  if (kcopy == NULL) return;
  memcpy(kcopy, key, klen + 1);
  g_handlers[g_n_handlers].key = kcopy;
  g_handlers[g_n_handlers].invoke = invoke;
  g_handlers[g_n_handlers].env = env;
  g_n_handlers++;
}

FenelHandlerEntry *fenel_lookup_handler(const char *key) {
  for (int i = 0; i < g_n_handlers; i++) {
    if (strcmp(g_handlers[i].key, key) == 0) return &g_handlers[i];
  }
  return NULL;
}

void fenel_reset_handlers(void) {
  for (int i = 0; i < g_n_handlers; i++) {
    free(g_handlers[i].key);
    g_handlers[i].key = NULL;
    g_handlers[i].invoke = NULL;
    g_handlers[i].env = NULL;
  }
  g_n_handlers = 0;
}

/* ---------------------------------------------------------------------------
 * Per-(Class, method) effect shims
 *
 * The auto-generation lives in the test harness — given a `LlvmModule`'s
 * `effectImports` array, the harness emits one C function per entry:
 *
 *   void *fenel_<Class>_<method>(void *a0, void *a1, ..., void *aN) {
 *     FenelHandlerEntry *h = fenel_lookup_handler("<Class>:<method>");
 *     if (h == NULL) return NULL;
 *     void *args[N] = { a0, a1, ..., aN };
 *     return h->invoke(h->env, args, N);
 *   }
 *
 * (For arity-0 methods, the args[] array is omitted and `n = 0` is passed.)
 *
 * This file deliberately does not hard-code any specific (Class, method)
 * pair — those names are program-specific and live with the program's
 * effect surface. The auto-generated shim links alongside this file via
 * the test harness's `clang -shared` invocation.
 * ---------------------------------------------------------------------------
 */
