/**
 * Generate `src/generated/parser-bootstrap.generated.ts` — the bootstrap
 * pre-parse artifact for parser-substrate Phase 5c (the init-cycle dissolution,
 * P0 §7).
 *
 * The Fenel parser (at 5d) cannot self-parse the files that load BEFORE it is
 * registered: every `.fenel` source `type-foundation.ts` imports at module-init
 * (parsed before `stdModule`/`engineModule`, which carry the parser bodies,
 * exist) PLUS `parser-fixities.fenel` (the lexer's localized-operator / fixity
 * table, read at tokenize time — §6). This artifact carries the pre-parsed
 * program JSON for that exact set, so the Fenel parser can boot the files it
 * can't yet parse for itself.
 *
 * The init-cycle file SET is derived empirically, not guessed: the `?raw`
 * imports of `type-foundation.ts` (the genuine "parsed before any parser exists"
 * set — S0 audit §4) ∪ `parser-fixities.fenel` ∪ the deliberately broad regex-
 * carrier scan under `fenel/`.
 *
 * This artifact is the cold-cache second lookup in `parsedViaCache`, so it is
 * on the boot path. The payload is the SAME parser-agnostic contract as the
 * parse-cache: each entry's pre-parsed JSON ≡ `parse(src)` byte-for-byte
 * (asserted by the generator).
 *
 * Hash-gated: `PARSER_BOOTSTRAP_SOURCE_HASH` digests the (relpath, srcHash)
 * pairs; a stale artifact never silently serves (the compiled-parser manifest-
 * hash precedent).
 *
 * Run:
 *   bun implementations/typescript/engine/scripts/generate-parser-bootstrap.ts
 *   bun implementations/typescript/engine/scripts/generate-parser-bootstrap.ts --check
 */

import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  bootstrapInitCycleFiles,
} from "./lib/bootstrap-carriers";
import { parseCacheKey } from "../src/parse-cache-key";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..", "..");
const ENGINE_SRC = join(HERE, "..", "src");
const ARTIFACT_PATH = join(ENGINE_SRC, "generated", "parser-bootstrap.generated.ts");

type BuildDependencies = {
  readonly parse: (source: string) => unknown;
  readonly withInterpretedResolver: <T>(fn: () => T) => T;
  readonly astAbiVersion: number;
  readonly assertJsonValue: (value: unknown) => void;
};

function build(dependencies: BuildDependencies): {
  json: string;
  sourceHash: string;
  count: number;
  astAbiVersion: number;
} {
  // Some init-cycle files contain regex set forms whose TS parse reaches the
  // Fenel regex marker body. The complete bootstrap scan is one finite proof;
  // keep it interpreted so a stale compiled resolver cannot recursively
  // re-prove changing registry inputs while this foundational artifact builds.
  return dependencies.withInterpretedResolver(() => {
  const files = bootstrapInitCycleFiles({ repoRoot: ROOT, engineSrc: ENGINE_SRC });
  const entries: Record<string, { srcHash: string; ast: unknown; source: string }> = {};
  const hashPairs: string[] = [];
  for (const rel of files) {
    // LF-canonical read (K0-repair-3): artifact keys/values must be
    // checkout-endings-independent; idempotent once parseCacheKey normalizes.
    const src = readFileSync(join(ROOT, rel), "utf8").replace(/\r\n?/g, "\n");
    let ast: unknown;
    try {
      ast = dependencies.parse(src);
    } catch (e) {
      throw new Error(`parser-bootstrap: init-cycle file failed to parse: ${rel} — ${String(e).slice(0, 160)}`);
    }
    // Assert the round-trip is byte-identical (the parser-agnostic contract — a
    // bootstrap entry must equal parse(src) exactly so the 5d flip is a byte-diff
    // on the same payload).
    dependencies.assertJsonValue(ast);
    const roundTripped = JSON.parse(JSON.stringify(ast));
    if (JSON.stringify(ast) !== JSON.stringify(roundTripped)) {
      throw new Error(`parser-bootstrap: ${rel} is not JSON-lossless — the bootstrap payload contract is violated.`);
    }
    const srcHash = parseCacheKey(src);
    entries[rel] = { srcHash, ast: roundTripped, source: src };
    hashPairs.push(`${rel}:${srcHash}`);
  }
  // The gate hash: a content digest of the (relpath, srcHash) pairs. cyrb53 via
  // parseCacheKey over the joined manifest (sync + browser-safe, same primitive
  // the cache key uses).
  const sourceHash = parseCacheKey(hashPairs.join("\n"));
  return {
    json: JSON.stringify(entries),
    sourceHash,
    count: files.length,
    astAbiVersion: dependencies.astAbiVersion,
  };
  });
}

function render(b: ReturnType<typeof build>): string {
  return `// GENERATED by scripts/generate-parser-bootstrap.ts — DO NOT EDIT.
//
// parser-substrate Phase 5c — the bootstrap pre-parse artifact (P0 §7). Carries
// the pre-parsed program JSON for the three-part init-cycle union: the \`?raw\`
// imports of type-foundation.ts ∪ parser-fixities.fenel ∪ the deliberately broad
// regex-carrier scan under fenel/. It is the cold-cache second lookup in
// parsedViaCache, so it IS on the boot path. PARSER_BOOTSTRAP_SOURCE_HASH gates
// staleness.
// Regenerate after editing any init-cycle source (or type-foundation's import set):
//   bun implementations/typescript/engine/scripts/generate-parser-bootstrap.ts
//   bun implementations/typescript/engine/scripts/generate-parser-bootstrap.ts --check
/* eslint-disable */

export const PARSER_BOOTSTRAP_VERSION = ${b.astAbiVersion};
export const PARSER_BOOTSTRAP_COUNT = ${b.count};
export const PARSER_BOOTSTRAP_SOURCE_HASH = ${JSON.stringify(b.sourceHash)};
/** { "<repo-relpath>": { srcHash, ast, source } } — pre-parsed JSON and exact warmup bytes. */
export const PARSER_BOOTSTRAP_JSON = ${JSON.stringify(b.json)};
`;
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const preflightOnly = process.argv.includes("--preflight");
  // Recovery for an older, uncommitted seed without embedded source bytes.
  // Supplied bytes receive the same exact-key verification as Git history;
  // this option cannot bypass an ABI, carrier, or source-hash refusal.
  const recoveryPath = process.argv.find((arg) => arg.startsWith("--historical-sources="))?.slice("--historical-sources=".length);
  const recordedSources: unknown = recoveryPath ? JSON.parse(readFileSync(recoveryPath, "utf8")) : undefined;
  if (recordedSources !== undefined && (recordedSources === null || typeof recordedSources !== "object"
    || Array.isArray(recordedSources) || Object.values(recordedSources).some((source) => typeof source !== "string"))) {
    throw new Error("Historical sources must be a JSON object mapping repository paths to source text");
  }
  // MUST precede every engine import. The recorded seed is the only safe source
  // of carrier ASTs while the module graph is cold; importing the parser first
  // would recreate the failure this preflight is meant to name.
  const { prepareBootstrapSources, withBootstrapSources } = await import("./lib/bootstrap-source-plan");
  const plan = prepareBootstrapSources({ repoRoot: ROOT, engineSrc: ENGINE_SRC, recordedSources: recordedSources as Record<string, string> | undefined });
  if (preflightOnly) {
    console.log(JSON.stringify({ ok: plan.ok, warnings: plan.warnings, refusals: plan.refusals }));
    process.exitCode = plan.ok ? 0 : 1;
    return;
  }
  for (const warning of plan.warnings) {
    console.warn(`[parser-bootstrap:preflight] WARN — ${warning}`);
  }
  if (!plan.ok) {
    for (const refusal of plan.refusals) {
      console.error(`[parser-bootstrap:preflight] REFUSED — ${refusal}`);
    }
    console.error(
      "[parser-bootstrap:preflight] Historical bootstrap needs a blob matching each recorded seed key. "
      + "Brand-new early-init carriers still require a separately verified bootstrap; see "
      + "workstreams/module-substrate/briefs/phase-m3-boot-artifact-hygiene-driver-and-bootstrap.md.",
    );
    process.exitCode = 1;
    return;
  }

  const b = await withBootstrapSources(plan, async () => {
    await import("../src/fenel-parser");
    const dispatch = await import("../src/engine-bodies-dispatch");
    dispatch.withInterpretedResolver(() => dispatch.dispatchEngineBody("engine:humanizeCodeName", ["bootstrapProbe"]));
  }, async () => {
    const parserModule = await import("../src/fenel-parser");
    const dispatchModule = await import("../src/engine-bodies-dispatch");
    const cacheModule = await import("../src/parse-cache");
    const { assertJsonAuthoringValue } = await import("../src/authoring/json-value");
    return build({
      parse: parserModule.parse,
      withInterpretedResolver: dispatchModule.withInterpretedResolver,
      astAbiVersion: cacheModule.PARSER_BOOTSTRAP_AST_ABI_VERSION,
      assertJsonValue: assertJsonAuthoringValue,
    });
  });
  const generated = render(b);

  if (check) {
    let existing: string;
    try {
      existing = readFileSync(ARTIFACT_PATH, "utf8");
    } catch {
      console.error(`[parser-bootstrap:check] ${ARTIFACT_PATH} not found — run without --check first.`);
      process.exitCode = 1;
      return;
    }
    const norm = (s: string): string => s.replace(/\r\n/g, "\n");
    if (norm(existing) === norm(generated)) {
      console.log(`[parser-bootstrap:check] OK — committed artifact matches the ${b.count} init-cycle sources.`);
      return;
    }
    console.error(
      "[parser-bootstrap:check] DRIFT — committed artifact differs from what the live init-cycle sources would generate. Re-run without --check + commit.",
    );
    process.exitCode = 1;
    return;
  }

  mkdirSync(dirname(ARTIFACT_PATH), { recursive: true });
  writeFileSync(ARTIFACT_PATH, generated, "utf8");
  console.log(`[parser-bootstrap] wrote ${ARTIFACT_PATH} — ${b.count} init-cycle files.`);
}

if (import.meta.main) {
  void main().catch((error) => {
    console.error("parser-bootstrap failed:", error);
    process.exitCode = 1;
  });
}
