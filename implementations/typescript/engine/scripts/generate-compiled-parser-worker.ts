function withCompiledRecoveryControls<T>(
  dependencies: BuildDependencies,
  operation: (() => T) & (
    Extract<T, PromiseLike<unknown>> extends never ? unknown : never
  ),
): T {
  const previousCache = dependencies.parseCache.parseCacheEnabled();
  const previousLegacy = dependencies.parseCache.fenelParserLegacy();
  dependencies.parseCache.setParseCacheEnabled(false);
  dependencies.parseCache.setFenelParserLegacy(true);
  try {
    if (
      dependencies.parseCache.parseCacheEnabled()
      || !dependencies.parseCache.fenelParserLegacy()
    ) {
      throw new Error("compiled-parser recovery controls were not installed");
    }
    return dependencies.dispatch.withInterpretedCompiledArtifacts(operation);
  } finally {
    dependencies.parseCache.setFenelParserLegacy(previousLegacy);
    dependencies.parseCache.setParseCacheEnabled(previousCache);
    if (
      dependencies.parseCache.parseCacheEnabled() !== previousCache
      || dependencies.parseCache.fenelParserLegacy() !== previousLegacy
    ) {
      throw new Error("compiled-parser recovery controls were not restored");
    }
  }
}

// The base-runtime natives the runtime hook supplies in JS-function-form (the
// $fenelBaseRuntime role). The generator ASSERTS the closure references no
// native outside this set — a new one must be added to the runtime in the
// hook (and here) deliberately, never silently.
export const KNOWN_PARSER_NATIVES: ReadonlySet<string> = new Set<string>([
  "$structuralTruthy", "and", "or", "std:and", "std:or",
  "appendItem", "at", "charFromCode", "chars", "concat", "contains", "elem", "entries", "filter", "floor",
  "fromEntries", "hasOwn", "head", "isArray", "isBoolean", "isNull", "isNumber", "isString", "join", "length", "lookup", "lower", "map", "mapGet", "mapSet", "matchFail", "replaceAll",
  "slice", "startsWith", "tail", "toNumber", "toString",
]);

// The nullary-constructor-as-value bindings the runtime closes over (a bare
// `Nothing` / `True` / `False` reference in the compiled JS). The generator
// asserts no OTHER bare Capitalized identifier escapes (a new one would be a
// missing constructor binding).
const KNOWN_CTOR_BINDINGS = new Set<string>(["Nothing", "True", "False"]);

const shortCode = (id: string): string => (id.includes(":") ? id.slice(id.indexOf(":") + 1) : id);

/** C2 preparation only. This is not a complete reusable-input certificate. */
function prepareCompiledParserInsideRecovery(
  dependencies: BuildDependencies,
): PreparedCompiledArtifact {

  const { createRepositoryRegistry } = dependencies.repositoryRegistry;
  const { createEngineBootstrapRegistry } = dependencies.registry;
  const { stdModule } = dependencies.std;
  const { engineModule } = dependencies.engine;
  const { localeModule } = dependencies.locale;
  const { COMPILER_TARGET_ENTITY_MODULES } = dependencies.targetEntities;
  const {
    computeParserClosureIds,
    computeParserEntryClosureIds,
    compiledArtifactBootstrapRuntimeInputHash,
    compiledArtifactRuntimeInputHash,
    compiledArtifactManifestHashesForBuild,
    PARSER_ENTRY_FN_IDS,
    PARSER_COMPILE_SEMANTIC_OWNER_IDS,
    PARSER_COMPILED_NATIVE_OVERRIDE_FN_IDS,
  } = dependencies.dispatch;
  const {
    compileConstructorSlotTable,
    compileConstructorSlotConflicts,
    compileConstructorWireNames,
    compileFunctionParamSlots,
    compileFunctionTypeOwnerIds,
  } = dependencies.fieldSlots;
  const { compileCallBindingsByFnId } = dependencies.callBindings;
  const { getRepositoryCompilerConstructorMetadataView } = dependencies.metadata;
  const { constraintsToRequiresStrings } = dependencies.effects;

  reportProgress("repository registry: start");
  const reg = createRepositoryRegistry(dependencies.provenance.observeOwnerModuleRoleInput("primary", "compiled-parser/primary", [
    stdModule,
    engineModule,
    localeModule,
    ...COMPILER_TARGET_ENTITY_MODULES,
  ]));
  reportProgress("repository registry: ready");
  const bootstrapReg = createEngineBootstrapRegistry(dependencies.provenance.observeOwnerModuleRoleInput("bootstrap", "compiled-parser/bootstrap", [
    stdModule,
    engineModule,
    localeModule,
    ...COMPILER_TARGET_ENTITY_MODULES,
  ]));
  reportProgress("bootstrap registry: ready");
  const closureIds = computeParserClosureIds(reg);
  const bootstrapClosureIds = computeParserClosureIds(bootstrapReg);
  if (JSON.stringify(bootstrapClosureIds) !== JSON.stringify(closureIds)) {
    throw new Error(
      "compiled-parser: authoritative/bootstrap whole closures differ",
    );
  }
  reportProgress("parser closure: ready", `${closureIds.length} functions`);
  reportProgress("parser manifest inputs: start");
  const manifestHashes = compiledArtifactManifestHashesForBuild("parser", reg);
  if (manifestHashes === null) {
    throw new Error("compiled-parser: Node hashing is unavailable");
  }
  reportProgress("parser manifest inputs: ready");
  const shards = Object.create(null) as Record<string, {
    closureIds: string[];
    manifestHash: string;
    runtimeInputHash: string;
    bootstrapRuntimeInputHash: string;
  }>;
  const shardUnion = new Set<string>();
  for (const entryFnId of PARSER_ENTRY_FN_IDS) {
    const shardClosureIds = computeParserEntryClosureIds(reg, entryFnId);
    const bootstrapShardClosureIds = computeParserEntryClosureIds(
      bootstrapReg,
      entryFnId,
    );
    if (JSON.stringify(bootstrapShardClosureIds) !== JSON.stringify(shardClosureIds)) {
      throw new Error(
        `compiled-parser: authoritative/bootstrap closures differ for ${entryFnId}`,
      );
    }
    for (const id of shardClosureIds) shardUnion.add(id);
    const manifestHash = manifestHashes.shards[entryFnId];
    if (manifestHash === undefined) {
      throw new Error(`compiled-parser: Node shard hashing is unavailable for ${entryFnId}`);
    }
    const shardRuntimeInputHash = compiledArtifactRuntimeInputHash(
      "parser",
      reg,
      entryFnId,
    );
    if (shardRuntimeInputHash === null) {
      throw new Error(`compiled-parser: Node shard runtime-input hashing is unavailable for ${entryFnId}`);
    }
    const shardBootstrapRuntimeInputHash = compiledArtifactBootstrapRuntimeInputHash(
      "parser",
      bootstrapReg,
      manifestHash,
      entryFnId,
    );
    if (shardBootstrapRuntimeInputHash === null) {
      throw new Error(`compiled-parser: Node shard bootstrap runtime-input hashing is unavailable for ${entryFnId}`);
    }
    shards[entryFnId] = {
      closureIds: shardClosureIds,
      manifestHash,
      runtimeInputHash: shardRuntimeInputHash,
      bootstrapRuntimeInputHash: shardBootstrapRuntimeInputHash,
    };
    reportProgress(
      "parser shard manifest: ready",
      `${entryFnId} (${shardClosureIds.length} functions)`,
    );
  }
  const unionClosureIds = [...shardUnion].sort();
  if (JSON.stringify(unionClosureIds) !== JSON.stringify(closureIds)) {
    throw new Error(
      "compiled-parser: per-entry shard union differs from the whole-artifact closure",
    );
  }
  const hash = manifestHashes.manifestHash;
  const runtimeInputHash = compiledArtifactRuntimeInputHash("parser", reg);
  if (runtimeInputHash === null) {
    throw new Error("compiled-parser: Node runtime-input hashing is unavailable");
  }
  const bootstrapRuntimeInputHash = compiledArtifactBootstrapRuntimeInputHash(
    "parser",
    bootstrapReg,
    hash,
  );
  if (bootstrapRuntimeInputHash === null) {
    throw new Error("compiled-parser: Node bootstrap runtime-input hashing is unavailable");
  }
  reportProgress("parser manifest: ready", hash);
  const compilerMetadata = getRepositoryCompilerConstructorMetadataView();
  reportProgress("compiler metadata: ready");
  const callBindingsByFnId = compileCallBindingsByFnId([stdModule, engineModule, localeModule]);
  reportProgress("call bindings: ready", `${callBindingsByFnId.size} functions`);
  const ctorDefsByOwnerKey = new Map<string, ReturnType<typeof compileConstructorSlotTable>>();

  const identifiedOwnerIds = new Set(
    compilerMetadata.listIdentifiedEntities().map((entity) => entity.id),
  );
  for (const ownerId of PARSER_COMPILE_SEMANTIC_OWNER_IDS) {
    if (!identifiedOwnerIds.has(ownerId)) {
      throw new Error(`compiled-parser: semantic owner ${ownerId} is absent from exact compiler metadata`);
    }
  }
  const artifactOwnerTable = compileConstructorSlotTable(compilerMetadata, {
    ownerIds: PARSER_COMPILE_SEMANTIC_OWNER_IDS,
  });
  reportProgress("artifact owner table: ready");
  const artifactOwnerConflicts = compileConstructorSlotConflicts(artifactOwnerTable);
  if (artifactOwnerConflicts.length > 0) {
    throw new Error(
      `compiled-parser: declared semantic owners conflict on ${artifactOwnerConflicts.join(", ")}`,
    );
  }

  // The checked-in artifact retains short code names as its loader ABI. Never
  // let two exact function owners silently overwrite one another in that map.
  const ownerByCode = new Map<string, string>();
  for (const id of closureIds) {
    const code = shortCode(id);
    const prior = ownerByCode.get(code);
    if (prior !== undefined && prior !== id) {
      throw new Error(`compiled-parser: short-code collision ${JSON.stringify(code)} for ${prior}/${id}`);
    }
    ownerByCode.set(code, id);
  }
  const allowedNativeOverrides = new Set<string>(PARSER_COMPILED_NATIVE_OVERRIDE_FN_IDS);
  for (const id of allowedNativeOverrides) {
    if (!closureIds.includes(id)) {
      throw new Error(`compiled-parser: stale native-override policy for absent closure id ${id}`);
    }
  }
  for (const id of closureIds) {
    const code = shortCode(id);
    const collidesWithNative = KNOWN_PARSER_NATIVES.has(code);
    const collidesWithCtorBinding = KNOWN_CTOR_BINDINGS.has(code);
    if (allowedNativeOverrides.has(id)) {
      if (!collidesWithNative || collidesWithCtorBinding) {
        throw new Error(`compiled-parser: invalid native-override policy for ${id}`);
      }
    } else if (collidesWithNative || collidesWithCtorBinding) {
      throw new Error(`compiled-parser: unapproved closure/runtime collision ${id} (${code})`);
    }
  }

  const cells: PreparedCompileCell[] = [];
  for (let closureIndex = 0; closureIndex < closureIds.length; closureIndex += 1) {
    const id = closureIds[closureIndex]!;
    reportProgress(
      "prepare source: start",
      `${closureIndex + 1}/${closureIds.length} ${id}`,
    );
    // The strict artifact registry owns the effective function/scheme for this
    // exact parser topology. Repository-wide metadata supplies only the
    // complete constructor/Field identity union below.
    const cell = capturePreparedCompileCell(id, () => {
      const fn = reg.getIdentifiedFunction(id);
      if (fn === undefined || fn.id !== id || fn.body === undefined) {
        return `${id}: no exact identified compiler definition / body`;
      }
      const preferredOwnerIds = [...new Set([
        ...PARSER_COMPILE_SEMANTIC_OWNER_IDS,
        ...compileFunctionTypeOwnerIds(fn),
      ])].sort();
      const ownerKey = preferredOwnerIds.join("\0");
      let ctorDefs = ctorDefsByOwnerKey.get(ownerKey);
      if (ctorDefs === undefined) {
        ctorDefs = compileConstructorSlotTable(compilerMetadata, { preferredOwnerIds });
        ctorDefsByOwnerKey.set(ownerKey, ctorDefs);
      }
      const callBindings = callBindingsByFnId.get(id);
      if (callBindings === undefined) {
        return `${id}: no immutable defining-module call bindings`;
      }
      const requires = fn.requires ?? [];
      const source: CompileSource = {
        name: id,
        params: compileFunctionParamSlots(fn),
        body: fn.body,
        ctorDefs,
        ctorWireNames: compileConstructorWireNames(ctorDefs),
        callBindings,
        ...(requires.length === 0 ? {} : { requires: constraintsToRequiresStrings(requires) }),
      };
      return prepareCompileSource(source, compileConstructorSlotConflicts(ctorDefs),
        dependencies.immutable.exactImmutableDataSnapshot, dependencies.callBindings.isCompilerOwnedCallBindings);
    });
    cells.push(cell);
    if (cell.status === "threw") break;
  }
  const entryCodes = Object.create(null) as Record<string, string>;
  for (const id of PARSER_ENTRY_FN_IDS) entryCodes[id] = shortCode(id);
  return Object.freeze({
    artifact: "compiled-parser" as const,
    metadata: immutablePreparationMetadata({
      identityDomain: dependencies.identityDomains.compiledIdentityInput("parser").domain,
      hash, runtimeInputHash, bootstrapRuntimeInputHash, entryCodes, closureIds, shards,
    }, dependencies.immutable.exactImmutableDataSnapshot),
    cells: Object.freeze(cells),
  });
}

function compilePreparedParser(
  dependencies: BuildDependencies,
  prepared: PreparedCompiledArtifact,
): {
  identityDomain: PreparedCompiledArtifact["metadata"]["identityDomain"];
  hash: string;
  runtimeInputHash: string;
  bootstrapRuntimeInputHash: string;
  entryCodes: Readonly<Record<string, string>>;
  closureIds: readonly string[];
  shards: PreparedCompiledArtifact["metadata"]["shards"];
  bodies: Record<string, string>;
  requiredNatives: string[];
} {
  const { hash, runtimeInputHash, bootstrapRuntimeInputHash, entryCodes, closureIds, shards } = prepared.metadata;
  const { compileFenelToJsNative } = dependencies.compileJs;
  const { dispatchedSerializeJsModule } = dependencies.dispatch;
  const bodies = Object.create(null) as Record<string, string>;
  const failures: string[] = [];
  const attempts = preparedCompileSourceAttempts(prepared.cells, failures,
    (id, closureIndex) => reportProgress("compile: start", `${closureIndex + 1}/${closureIds.length} ${id}`));
  for (const [closureIndex, input] of attempts) {
    const { name: id } = input.source;
    const source = input.source;
    const code = shortCode(id);
    const compiled = compileFenelToJsNative(source);
    if (compiled.$tag === "Err") {
      failures.push(`${id}: compile — ${JSON.stringify(compiled._0).slice(0, 160)}`);
      continue;
    }
    if (compiled._0.name !== id) {
      failures.push(`${id}: compiler returned mismatched module id ${JSON.stringify(compiled._0.name)}`);
      continue;
    }
    const serialised = dispatchedSerializeJsModule(compiled._0);
    if (serialised.$tag === "Err") {
      failures.push(`${id}: serialise — ${serialised._0}`);
      continue;
    }
    bodies[code] = serialised._0;
    reportProgress(
      "compile: ready",
      `${closureIndex + 1}/${closureIds.length} ${id}`,
    );
  }
  if (failures.length > 0) {
    throw new Error(
      `compiled-parser: ${failures.length} closure fn(s) failed to compile — the artifact cannot be generated:\n  ${failures.join("\n  ")}`,
    );
  }

  // Validate the runtime contract: every $fenel.X ref is a closure fn or a
  // KNOWN native; every bare Capitalized ref is a closure fn or a KNOWN ctor.
  const closureCodes = new Set(closureIds.map(shortCode));
  const refNative = /\$fenel\.([A-Za-z_$][\w$]*)/g;
  const refCap = /(?<![\w.$])([A-Z][A-Za-z0-9_]*)\b/g;
  const requiredNatives = new Set<string>();
  const unknownNatives = new Set<string>();
  const unknownFullIds = new Set<string>();
  const unknownCtors = new Set<string>();
  const closureIdSet = new Set(closureIds);
  for (const src of Object.values(bodies)) {
    let m: RegExpExecArray | null;
    while ((m = refNative.exec(src)) !== null) {
      const n = m[1]!;
      if (closureCodes.has(n)) continue;
      requiredNatives.add(n);
      if (!KNOWN_PARSER_NATIVES.has(n)) unknownNatives.add(n);
    }
    const refBracket = /\$fenel\[("(?:\\.|[^"\\])*")\]/g;
    while ((m = refBracket.exec(src)) !== null) {
      const n = JSON.parse(m[1]!) as string;
      if (closureIdSet.has(n) || closureCodes.has(n)) continue;
      if (n.includes(":")) {
        unknownFullIds.add(n);
        continue;
      }
      requiredNatives.add(n);
      if (!KNOWN_PARSER_NATIVES.has(n)) unknownNatives.add(n);
    }
    while ((m = refCap.exec(src)) !== null) {
      const n = m[1]!;
      if (closureCodes.has(n) || KNOWN_CTOR_BINDINGS.has(n)) continue;
      // Capitalized tokens inside string literals ("PAlt", "$tag":"SVar", …)
      // are not bare refs — only flag identifiers that aren't string contents.
      // A conservative heuristic: a genuine bare ctor ref appears as a bare
      // word; quoted ctor names appear inside "...". Skip names that ONLY ever
      // occur quoted by checking for an adjacent quote is unreliable, so we
      // instead require the name to also appear as a `$fenel`-free bare token
      // not preceded by a quote on its line. In practice the only bare ctor
      // values the pipeline emits as `{var}` are nullary ctors; applied ctors
      // lower to `{$tag:...}` object literals. Track for the report; do not
      // hard-fail on quoted-only names.
      unknownCtors.add(n);
    }
  }
  if (unknownNatives.size > 0) {
    throw new Error(
      `compiled-parser: closure references native(s) not in the runtime contract: ${[...unknownNatives].sort().join(", ")} — add them to the $fenel runtime in engine-bodies-dispatch.ts (and KNOWN_PARSER_NATIVES here).`,
    );
  }
  if (unknownFullIds.size > 0) {
    throw new Error(
      `compiled-parser: emitted canonical runtime ref(s) absent from the exact closure: ${[...unknownFullIds].sort().join(", ")}`,
    );
  }
  // Bare-ctor validation: filter to names that appear UNQUOTED (a bare ctor
  // value). We re-scan tolerating false positives from quoted ctor-name string
  // literals by removing string contents first.
  const stripStrings = (s: string): string => s.replace(/"(?:\\.|[^"\\])*"/g, '""');
  const genuineCtors = new Set<string>();
  for (const src of Object.values(bodies)) {
    const bare = stripStrings(src);
    let m: RegExpExecArray | null;
    const r = /(?<![\w.$])([A-Z][A-Za-z0-9_]*)\b/g;
    while ((m = r.exec(bare)) !== null) {
      const n = m[1]!;
      if (closureCodes.has(n) || KNOWN_CTOR_BINDINGS.has(n)) continue;
      genuineCtors.add(n);
    }
  }
  if (genuineCtors.size > 0) {
    throw new Error(
      `compiled-parser: closure emits bare constructor value(s) not in the runtime contract: ${[...genuineCtors].sort().join(", ")} — add a binding to the $fenel runtime in engine-bodies-dispatch.ts (and KNOWN_CTOR_BINDINGS here).`,
    );
  }


  return {
    identityDomain: prepared.metadata.identityDomain,
    hash,
    runtimeInputHash,
    bootstrapRuntimeInputHash,
    entryCodes,
    closureIds,
    shards,
    bodies,
    requiredNatives: [...requiredNatives].sort(),
  };
}

export function prepareCompiledParser(dependencies: BuildDependencies): PreparedCompiledArtifact {
  return withCompiledRecoveryControls(dependencies, () => prepareCompiledParserInsideRecovery(dependencies));
}

export function buildCompiledParser(dependencies: BuildDependencies,
  observePrepared?: (prepared: PreparedCompiledArtifact) => void): ReturnType<typeof compilePreparedParser> {
  return withCompiledRecoveryControls(dependencies, () => {
    const prepared = prepareCompiledParserInsideRecovery(dependencies);
    observePrepared?.(prepared);
    return compilePreparedParser(dependencies, prepared);
  });
}

/** Selected only by a captured bootstrap, never the public worker CLI.
 * The contract and origin recorder start before the first engine graph import.
 * This is diagnostic observation until identity-domain/hash integration lands.
 */
export async function runCompiledParserObservedWorkerMain(contract: "all" | "entity-envelope",
  requestedDomain?: CompiledIdentityDomain, operation: "render" | "prepare" = "render",
  policySource?: string): Promise<void> {
  if (operation !== "render" && operation !== "prepare") throw new Error("unknown parser producer observation operation");
  const { beginOwnerProducerInputScope } = await import("../src/owner-input-producer-state");
  const scope = beginOwnerProducerInputScope(contract);
  let recording: ReturnType<typeof import("../src/owner-input-provenance")["beginOwnerModuleProvenanceRecording"]> | undefined;
  let recordingClosed = false;
  let scopeClosed = false;
  try {
    const provenance = await import("../src/owner-input-provenance");
    recording = provenance.beginOwnerModuleProvenanceRecording();
    const dependencies = await loadBuildDependencies();
    const domain = requestedDomain === undefined
      ? dependencies.identityDomains.allCompiledIdentityDomain("compiled-parser")
      : dependencies.identityDomains.resolveRepositoryCompiledIdentityDomain(requestedDomain, "compiled-parser").domain;
    if (contract === "all" && domain.kind !== "all") throw new Error("broad parser producer cannot inherit an owner identity domain");
    let actualPrepared: PreparedCompiledArtifact | undefined;
    const bytes = dependencies.identityDomains.withCompiledIdentityDomain(domain, () => {
      if (operation === "prepare") {
        actualPrepared = prepareCompiledParser(dependencies);
        return undefined;
      }
      const built = withCompiledRecoveryControls(dependencies, () => buildCompiledParser(dependencies, prepared => { actualPrepared = prepared; }));
      return new TextEncoder().encode(renderCompiledParser(built));
    });
    if (actualPrepared === undefined) throw new Error("full parser producer did not expose its actual prepared inputs");
    const compileInputsPacket = encodePreparationObservation(actualPrepared, dependencies.transport.encodeReplayValue);
    const sourceEnvelopes = policySource === undefined ? [] : recording.canonicalEnvelopes(
      (await dependencies.inputPolicy.loadOwnerInputPolicy(policySource)).invoke("ownerinputpolicy:ownerEntityInputFields", []));
    recordingClosed = true;
    const roles = recording.finish();
    scopeClosed = true;
    const observedScope = scope.finish();
    if (operation === "prepare") {
      process.stdout.write(new TextDecoder().decode(encodePreparationContractObservation({
        schema: "fenel.compiled-artifact-preparation-contract-observation.v1", artifact: "compiled-parser", authority: "NONE",
        contract, catalogueAttempts: observedScope.catalogueAttempts, catalogueAttemptDoors: observedScope.catalogueAttemptDoors,
        compileInputsPacket, sourceRolesTransport: dependencies.transport.encodeReplayValue(roles),
      })));
      return;
    }
    if (bytes === undefined) throw new Error("parser render observation has no actual artifact bytes");
    process.stdout.write(new TextDecoder().decode(encodeProducerObservation({
      schema: "fenel.compiled-artifact-producer-observation.v1", artifact: "compiled-parser", authority: "NONE",
      contract, identityDomainEstablished: false, catalogueAttempts: observedScope.catalogueAttempts,
      bytesBase64: Buffer.from(bytes).toString("base64"), compileInputsPacket,
      sourceRolesTransport: dependencies.transport.encodeReplayValue(roles),
      sourceEnvelopesTransport: dependencies.transport.encodeReplayValue(sourceEnvelopes),
    })));
  } finally {
    try { if (!recordingClosed) recording?.finish(); }
    finally { if (!scopeClosed) scope.finish(); }
  }
}

/** First post-capture heavy checkpoint: actual preparation, zero compilation.
 * The default ALL identity domain isolates catalogue viability from scoped B1.
 */
export async function runCompiledParserPreparationContractWorkerMain(): Promise<void> {
  await runCompiledParserObservedWorkerMain("entity-envelope", undefined, "prepare");
}

/** Invoked only by a controller-selected immutable bootstrap; never a freshness verdict. */
export async function runCompiledParserPreparationWorkerMain(): Promise<void> {
  if (process.argv.slice(2).length !== 0) throw new Error("compiled preparation worker accepts no arguments");
  const dependencies = await loadBuildDependencies();
  const prepared = prepareCompiledParser(dependencies);
  process.stdout.write(encodePreparationObservation(prepared, dependencies.transport.encodeReplayValue));
}

export function renderCompiledParser(
  b: ReturnType<typeof buildCompiledParser>,
): string {
  const sortedCodes = Object.keys(b.bodies).sort();
  const bodyLines = sortedCodes.map((c) => `    [${JSON.stringify(c)}, ${JSON.stringify(b.bodies[c])}],`);
  const entryLines = Object.entries(b.entryCodes).map(([id, c]) => `    [${JSON.stringify(id)}, ${JSON.stringify(c)}],`);
  const shardLines = Object.entries(b.shards).map(([id, shard]) =>
    `    [${JSON.stringify(id)}, Object.freeze({ identityDomain: PARSER_IDENTITY_DOMAIN, closureIds: Object.freeze(${JSON.stringify(shard.closureIds)}), manifestHash: ${JSON.stringify(shard.manifestHash)}, runtimeInputHash: ${JSON.stringify(shard.runtimeInputHash)}, bootstrapRuntimeInputHash: ${JSON.stringify(shard.bootstrapRuntimeInputHash)} })],`
  );
  return `// GENERATED by scripts/generate-compiled-parser.ts — DO NOT EDIT.
//
// parser-substrate Phase 6a — the compiled-parser performance branch. Each
// entry below is the JS lowering (shipped self-host pipeline) of a Fenel
// parser body; the runtime dispatch hook in engine-bodies-dispatch.ts builds
// the namespace + serves each entry ONLY when its PARSER_SHARDS digest matches
// the live registry bodies. The scalar hashes remain whole-artifact cross-checks.
// Regenerate with the script above after any edit to the
// parser \`.fenel\` sources (lexer / layout / fixity-resolve / expr-grammar /
// decl-grammar / pattern-algebra) or to the compile pipeline.
/* eslint-disable */

/** Whole-artifact digest retained as a transition cross-check. */
export const PARSER_MANIFEST_HASH = ${JSON.stringify(b.hash)};

/** One validated domain shared by whole/shard/runtime/bootstrap proofs. */
export const PARSER_IDENTITY_DOMAIN = Object.freeze(${JSON.stringify(b.identityDomain)});

/** Whole-artifact runtime certificate retained as a transition cross-check. */
export const PARSER_RUNTIME_INPUT_HASH = ${JSON.stringify(b.runtimeInputHash)};

/** Whole-artifact certificate for private engine-bootstrap registries. */
export const PARSER_BOOTSTRAP_RUNTIME_INPUT_HASH = ${JSON.stringify(b.bootstrapRuntimeInputHash)};

/** Per-entry freshness shards. Each closure is independently hash-gated. */
export const PARSER_SHARDS: Readonly<Record<string, Readonly<{
  identityDomain: typeof PARSER_IDENTITY_DOMAIN;
  closureIds: readonly string[];
  manifestHash: string;
  runtimeInputHash: string;
  bootstrapRuntimeInputHash: string;
}>>> = Object.freeze(Object.assign(
  Object.create(null) as Record<string, Readonly<{
    identityDomain: typeof PARSER_IDENTITY_DOMAIN;
    closureIds: readonly string[];
    manifestHash: string;
    runtimeInputHash: string;
    bootstrapRuntimeInputHash: string;
  }>>,
  Object.fromEntries([
${shardLines.join("\n")}
  ]),
));

/** The parser entry fn-ids → their codeName (the namespace keys below). */
export const PARSER_ENTRY_CODES: Readonly<Record<string, string>> = Object.freeze(Object.assign(
  Object.create(null) as Record<string, string>,
  Object.fromEntries([
${entryLines.join("\n")}
  ]),
));

/** The transitive closure fn-ids (for reference / the manifest contract). */
export const PARSER_CLOSURE_IDS: readonly string[] = Object.freeze(${JSON.stringify(b.closureIds, null, 0)});

/** Base-runtime native names the compiled bodies reference (the $fenel runtime must supply each). */
export const PARSER_REQUIRED_NATIVES: readonly string[] = Object.freeze(${JSON.stringify(b.requiredNatives, null, 0)});

/** codeName → serialized JS function expression (closes over the $ns namespace). */
export const PARSER_FN_BODIES: Readonly<Record<string, string>> = Object.freeze(Object.assign(
  Object.create(null) as Record<string, string>,
  Object.fromEntries([
${bodyLines.join("\n")}
  ]),
));
`;
}

export async function renderCompiledParserBytes(): Promise<Uint8Array> {
  const dependencies = await loadBuildDependencies();
  const built = withCompiledRecoveryControls(
    dependencies,
    () => buildCompiledParser(dependencies),
  );
  const rendered = renderCompiledParser(built);
  if (!rendered.endsWith("\n") || rendered.includes("\r")) {
    throw new Error("compiled-parser render must be exact UTF-8 LF bytes");
  }
  return new TextEncoder().encode(rendered);
}

export async function runCompiledParserWorkerMain(): Promise<void> {
  const unknown = process.argv.slice(2);
  if (unknown.length !== 0) {
    console.error(`[compiled-parser-worker] unexpected arguments: ${unknown.join(" ")}`);
    throw new Error("compiled-parser worker accepts no arguments");
  }
  const bytes = await renderCompiledParserBytes();
  process.stdout.write(`${JSON.stringify({
    schema: "fenel.compiled-artifact-render.v1",
    artifact: "compiled-parser",
    bytesBase64: Buffer.from(bytes).toString("base64"),
  })}\n`);
}

if (import.meta.main) await runCompiledParserWorkerMain();
