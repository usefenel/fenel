/**
 * Generate `src/generated/compiled-parser.generated.ts` — the compiled-parser
 * PERFORMANCE BRANCH for parser-substrate Phase 6a.
 *
 * The Fenel parser's seven entry bodies (engine:defaultFixityTable / lexAll /
 * layoutTokens / parseExprToks / parseProgToks / spliceSetBodies /
 * splitTopLevelDecls), plus their
 * generated transitive Fenel-bodied closure, are lowered to JS once by the
 * SHIPPED self-host pipeline (compileFenelToJs → serializeJsModule, all
 * Fenel-bodied, 21.10.1) and checked in as data-as-code. The runtime dispatch
 * hook (engine-bodies-dispatch.ts) serves the compiled path ONLY when the
 * embedded entry-shard manifest hash matches the live registry bodies. The
 * retained whole-artifact hash is a transition cross-check, not the serving
 * boundary.
 *
 * This is the CLAUDE.md opaque-repr-for-functions pattern: the `.fenel` bodies
 * stay the registry bodies + source of truth; this artifact is GENERATED from
 * them. It is NOT a natives-map shadow.
 *
 * Run:
 *   bun implementations/typescript/engine/scripts/generate-compiled-parser.ts
 *   bun implementations/typescript/engine/scripts/generate-compiled-parser.ts --check
 *
 * `--check` re-generates in-memory and diffs against the committed file,
 * exiting non-zero on drift (CI mode — the matrix / codename-lock precedent).
 */

