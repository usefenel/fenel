import { parse } from "./fenel-parser";
import { PARSE_VIA_FENEL_FAIL, parseViaFenelParser } from "./engine-bodies-dispatch";
import { getSystemRegistry } from "./system-registry";
import { timeModule } from "./modules/time";
import { evaluate, moduleSourceCoordinate, pureEvaluateContext, type EvaluateContext } from "./json-logic";
import { callableTypeArgumentKind, assertCallableTypeFamilyArguments, type CallableTypeFamilyOwner } from "./callable-type-families";
import { validateValue, type ValidationAdmissionObservation } from "./validate";
import { getCatalog } from "./type-catalog";
import { buildAuthoringCatalogSnapshot } from "./authoring/environment";
import type { ModuleRegistry } from "./registry";
import type { FenelType } from "./types";
import TIME_SOURCE from "../../../../fenel/modules/time/time.fenel?raw";

const VALID = [
  ["0001-01-01", { year: 1, month: 1, day: 1 }],
  ["0099-12-31", { year: 99, month: 12, day: 31 }],
  ["0400-02-29", { year: 400, month: 2, day: 29 }],
  ["1900-02-28", { year: 1900, month: 2, day: 28 }],
  ["2000-02-29", { year: 2000, month: 2, day: 29 }],
  ["2024-02-29", { year: 2024, month: 2, day: 29 }],
  ["2024-04-30", { year: 2024, month: 4, day: 30 }],
  ["2024-12-31", { year: 2024, month: 12, day: 31 }],
  ["2400-02-29", { year: 2400, month: 2, day: 29 }],
  ["9999-12-31", { year: 9999, month: 12, day: 31 }],
] as const;

const INVALID_TEXT: readonly unknown[] = [
  "", "not a date", "0000-01-01", "10000-01-01", "-001-01-01",
  "1900-02-29", "2100-02-29", "2023-02-29", "2024-02-30",
  "2024-00-01", "2024-13-01", "2024-01-00", "2024-01-32", "2024-04-31",
  "2024-2-29", "2024-02-9", "24-02-29", "2024/02/29", "Feb 29 2024",
  " 2024-02-29", "2024-02-29 ", "2024-02-29\n", "２０２４-０２-２９",
  "2024-02-29T00:00:00.000Z", "2024-02-29+00:00", "2024-02-29T25:99",
  7, null, { year: 2024, month: 2, day: 29 },
];

const INVALID_VALUE: readonly unknown[] = [
  { year: 0, month: 1, day: 1 }, { year: 10000, month: 1, day: 1 },
  { year: 2024.5, month: 1, day: 1 }, { year: 2024, month: 2.5, day: 1 },
  { year: 2024, month: 2, day: 1.5 }, { year: 2024, month: 2, day: 30 },
  { year: 1900, month: 2, day: 29 }, { year: 2024, month: 13, day: 1 },
  { year: 2024, month: 1, day: 0 }, { year: "2024", month: 2, day: 29 },
  { year: Number.NaN, month: 1, day: 1 }, { year: Number.POSITIVE_INFINITY, month: 1, day: 1 },
  { year: 2024, month: 2 }, { year: 2024, month: 2, day: 29, hour: 0 },
  { $tag: "Date", year: 2024, month: 2, day: 29 },
  "2024-02-29", [2024, 2, 29], 7, null,
];

describe("CalendarDate source — both existing parsers", () => {
  it("preserves the complete temporal source tree, including the refined record and codec", () => {
    // Full module verification uses the existing certified 4096-token lane.
    // Its unavailable/stale artifact refusal is not an interactive-parser pass.
    const fenelTree = parseViaFenelParser(TIME_SOURCE, { mode: "build-verification" });
    expect(fenelTree).not.toBe(PARSE_VIA_FENEL_FAIL);
    expect(fenelTree).toEqual(parse(TIME_SOURCE));
  }, 180_000);
});

describe("CalendarDate — existing source owner, membership and explicit codec", () => {
  let registry: ModuleRegistry;
  let reader: EvaluateContext;
  let owner: CallableTypeFamilyOwner;
  let exact: FenelType;

  beforeAll(() => {
    // The ordinary repository lock must be generated by the owner driver first.
    // A missing owner/identity is a failed setup, never a fabricated fixture.
    registry = getSystemRegistry();
    reader = pureEvaluateContext(registry.evaluateContext());
    const selected = reader._typeFamilyOwner?.("CalendarDate", moduleSourceCoordinate("time"));
    if (selected === undefined) throw new Error("CalendarDate has no admitted time source owner; generate the normal identity artifacts before this gate.");
    owner = selected;
    exact = { $ref: owner.identity };
  }, 180_000);

  const call = (name: string, ...args: unknown[]): unknown =>
    evaluate({ call: [`time:${name}`, ...args] } as never, {}, reader);

  const formChecked = (schema: FenelType, value: unknown) => validateValue(schema, value, null, {
    registry, functions: reader, coerce: false,
    strict: { membership: true, primitiveTypes: true, rejectAdded: false, rejectOmitted: true },
  });

  // The existing observation hook selects original-input admission mode.
  // Form output validity alone is not the actual literalMembershipFor verdict;
  // the frontend CalendarDate gate exercises that caller separately.
  const admissionChecked = (schema: FenelType, value: unknown) => {
    const plans: ValidationAdmissionObservation[] = [];
    const result = validateValue(schema, value, null, {
      registry, functions: reader, coerce: false,
      strict: { membership: true, primitiveTypes: true, rejectAdded: false, rejectOmitted: true },
      observeAdmission: plan => plans.push(plan),
    });
    return { ...result, plans };
  };

  it("uses one real CalendarDate owner and its declaration scope without capturing Date", () => {
    expect(owner.name).toBe("CalendarDate");
    expect(owner.ownerIdentity).toBe(registry.getEntityNominalIdentity("CalendarDate")!);
    expect(owner.identity).toBe(registry.getUuid("CalendarDate")!);
    expect(reader._typeFamilyOwner?.(owner.identity)?.ownerIdentity).toBe(owner.ownerIdentity);
    expect(reader._typeDeclarationScope?.(owner.ownerIdentity)?.sourceFunction).toBe(moduleSourceCoordinate("time"));
    expect(callableTypeArgumentKind(exact, reader)).toEqual({ $tag: "Just", _0: { $tag: "KType" } });
    expect(reader._typeFamilyOwner?.("CalendarDate", moduleSourceCoordinate("std"))).toBeUndefined();
    expect(reader._typeFamilyOwner?.("CalendarDateMissing", moduleSourceCoordinate("time"))).toBeUndefined();
    expect(reader._typeFamilyOwner?.("Date", moduleSourceCoordinate("time"))).toBeUndefined();
    expect(reader.getEntityType?.("Date")).toBeUndefined();
    expect(registry.getIdentifiedEntity("Date")).toBeUndefined();
    expect(callableTypeArgumentKind({ $ref: "Date" }, reader)).toEqual({ $tag: "Nothing" });
  });

  it("passes the existing ordinary type-family argument checker without a Date exception", () => {
    const listOwner = reader._typeFamilyOwner?.("List");
    if (listOwner === undefined) throw new Error("Existing List owner unavailable");
    expect(assertCallableTypeFamilyArguments(listOwner, [exact], reader)).toEqual({ $tag: "KType" });
    expect(() => assertCallableTypeFamilyArguments(listOwner, [{ $ref: "Date" }], reader)).toThrow(/no established/i);
  });

  it("has exactly the admitted Gregorian days, including century leap boundaries", () => {
    for (const [text, value] of VALID) {
      expect(admissionChecked(exact, value).valid, text).toBe(true);
      expect(call("calendarDate", value.year, value.month, value.day), text).toEqual({ $tag: "Ok", _0: value });
    }
    for (const value of INVALID_VALUE) {
      expect(admissionChecked(exact, value).valid, JSON.stringify(value)).toBe(false);
      expect(call("encodeCalendarDate", value)).toMatchObject({ $tag: "Err" });
    }
    // A codec checks its original argument even when ordinary form mode
    // can normalize an additional field out of its returned projection.
    expect(call("calendarDateValid", { year: 2024, month: 2, day: 29, note: "retained" })).toBe(false);
  }, 180_000);

  it("keeps form projection separate from original-input refinement admission", () => {
    const projected = { year: 2024, month: 2, day: 29 };
    for (const original of [
      { ...projected, hour: 0 },
      { $tag: "Date", ...projected },
    ]) {
      const before = structuredClone(original);
      const form = formChecked(exact, original);
      expect(form.valid).toBe(true);
      expect(form.value).toEqual(projected);
      const admission = admissionChecked(exact, original);
      expect(admission.valid).toBe(false);
      expect(admission.plans.at(-1)).toEqual({
        $tag: "ValidationAdmissionMember", verdict: { $tag: "Just", _0: false },
      });
      expect(call("calendarDateValid", original)).toBe(false);
      expect(call("encodeCalendarDate", original)).toMatchObject({ $tag: "Err" });
      expect(original).toEqual(before);
    }
  }, 180_000);

  it("covers every month boundary in a leap and a common year", () => {
    for (const [year, lengths] of [
      [2023, [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]],
      [2024, [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]],
    ] as const) {
      for (let index = 0; index < lengths.length; index += 1) {
        const month = index + 1;
        const last = lengths[index]!;
        expect(call("calendarDate", year, month, last)).toEqual({ $tag: "Ok", _0: { year, month, day: last } });
        expect(call("calendarDate", year, month, last + 1)).toMatchObject({ $tag: "Err" });
      }
    }
  });

  it("encodes every admitted sample successfully and roundtrips through canonical text", () => {
    for (const [text, value] of VALID) {
      // Stronger than Iso's vacuous error arms: neither direction may Err here.
      expect(call("encodeCalendarDate", value), text).toEqual({ $tag: "Ok", _0: text });
      expect(call("decodeCalendarDate", text), text).toEqual({ $tag: "Ok", _0: value });
    }
    expect(call("encodeCalendarDate", { day: 29, month: 2, year: 2024 })).toEqual({ $tag: "Ok", _0: "2024-02-29" });
  });

  it("refuses noncanonical text, invalid days, timestamps and wrong carriers without defaults", () => {
    for (const text of INVALID_TEXT) {
      expect(call("decodeCalendarDate", text), JSON.stringify(text)).toMatchObject({ $tag: "Err" });
    }
  });

  it("attaches the checked codec through the existing Iso instance and exact function references", () => {
    const codecs = timeModule.instances?.filter(instance =>
      instance.typeName === "Iso" && JSON.stringify(instance.args) === JSON.stringify(["String", "CalendarDate"]));
    expect(codecs).toHaveLength(1);
    const methods = codecs![0]!.methods;
    expect(methods.encode).toEqual({ $ref: "time.encodeCalendarDate" });
    expect(methods.decode).toEqual({ $ref: "time.decodeCalendarDate" });
    for (const [text, value] of VALID) {
      expect(evaluate({ call: [methods.encode, value] } as never, {}, reader)).toEqual({ $tag: "Ok", _0: text });
      expect(evaluate({ call: [methods.decode, text] } as never, {}, reader)).toEqual({ $tag: "Ok", _0: value });
    }
  });

  it("keeps the existing Date atom separate through the actual authoring catalogue deduplication", () => {
    // The strict seed catalogue (the system registry carries no state module).
    const sections = getCatalog();
    const rows = sections.flatMap(section => section.entries);
    expect(rows.find(row => row.id === "date")).toEqual({
      id: "date", name: "Date/Time Interval",
      description: "Calendar date or datetime — constrained by interval",
      category: "atom", tags: ["temporal", "primitive"],
    });
    const calendarRow = rows.find(row => row.entity?.id === "CalendarDate");
    expect(calendarRow?.name).toBe("Date");
    expect(calendarRow?.entity?.type).toBeDefined();
    const snapshot = buildAuthoringCatalogSnapshot(sections, { registry });
    const oldDate = snapshot.types.filter(row => row.name === "Date/Time Interval");
    const calendarDate = snapshot.types.filter(row => row.name === "Date");
    expect(oldDate).toHaveLength(1);
    expect(calendarDate).toHaveLength(1);
    expect(oldDate[0]?.id).toBe("date");
    expect(calendarDate[0]?.id).toBe(calendarRow?.id);
    expect(oldDate[0]?.entityId).toBeUndefined();
    expect(oldDate[0]?.type).toBeUndefined();
    expect(calendarDate[0]?.entityId).toBe("CalendarDate");
    expect(calendarDate[0]?.type).toBeDefined();
    expect(calendarDate[0]?.id).not.toBe(oldDate[0]?.id);
  }, 180_000);

  it("retains strict legacy Date-text behavior without turning it into CalendarDate membership", () => {
    const legacy: FenelType = { $ref: "Date" };
    const value = "2024-02-29T00:00:00.000Z";
    expect(formChecked(legacy, value)).toMatchObject({ valid: true, value });
    expect(formChecked(legacy, "not a date").valid).toBe(false);
    expect(formChecked(legacy, 7).valid).toBe(false);
    expect(admissionChecked(exact, value).valid).toBe(false);
    expect(formChecked(legacy, { year: 2024, month: 2, day: 29 }).valid).toBe(false);
    expect(timeModule.entities?.some(entity => entity.id === "Date" || entity.codeName === "Date")).toBe(false);
    expect(timeModule.instances?.some(instance =>
      instance.typeName === "Aliasable" && JSON.stringify(instance).includes('"Date"'))).toBe(false);
  }, 180_000);
});
