-- 0005_countries_geographical_sets.sql
-- Reference country data + geographical sets for geo-targeting

CREATE TABLE countries (
  code       TEXT PRIMARY KEY,
  alpha3     TEXT NOT NULL UNIQUE,
  name       TEXT NOT NULL,
  dial_code  TEXT NOT NULL,
  currency   TEXT NOT NULL,
  language   TEXT NOT NULL
);

CREATE TABLE geographical_sets (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id  UUID NOT NULL REFERENCES accounts(id),
  name        TEXT NOT NULL,
  description TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX geographical_sets_account_name_idx ON geographical_sets(account_id, name);

CREATE TABLE geographical_set_countries (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  set_id        UUID NOT NULL REFERENCES geographical_sets(id) ON DELETE CASCADE,
  country_code  TEXT NOT NULL REFERENCES countries(code),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX geo_set_countries_unique_idx ON geographical_set_countries(set_id, country_code);
CREATE INDEX geo_set_countries_set_idx ON geographical_set_countries(set_id);

